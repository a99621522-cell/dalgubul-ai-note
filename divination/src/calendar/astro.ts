const DEG = Math.PI / 180;
const J2000 = 2451545.0;

/** 그레고리력 → 율리우스일(UT). 시각은 0~24h 소수 */
export function jdFromCivil(y: number, m: number, d: number, hours = 0): number {
  if (m <= 2) { y -= 1; m += 12; }
  const A = Math.floor(y / 100);
  const B = 2 - A + Math.floor(A / 4);
  return Math.floor(365.25 * (y + 4716)) + Math.floor(30.6001 * (m + 1)) + d + B - 1524.5 + hours / 24;
}

export interface Civil { y: number; m: number; d: number; hh: number; mm: number; ss: number }

/** 율리우스일 → 그레고리력(소수 포함) */
export function civilFromJd(jd: number): Civil {
  const Z = Math.floor(jd + 0.5);
  const F = jd + 0.5 - Z;
  const alpha = Math.floor((Z - 1867216.25) / 36524.25);
  const A = Z + 1 + alpha - Math.floor(alpha / 4);
  const B = A + 1524;
  const C = Math.floor((B - 122.1) / 365.25);
  const D = Math.floor(365.25 * C);
  const E = Math.floor((B - D) / 30.6001);
  const day = B - D - Math.floor(30.6001 * E);
  const m = E < 14 ? E - 1 : E - 13;
  const y = m > 2 ? C - 4716 : C - 4715;
  let secs = Math.round(F * 86400);
  const hh = Math.floor(secs / 3600); secs -= hh * 3600;
  const mm = Math.floor(secs / 60); secs -= mm * 60;
  return { y, m, d: day, hh, mm, ss: secs };
}

/** ΔT = TT − UT (초). Espenak & Meeus 다항식, 1900~2150 */
export function deltaT(year: number, month = 6): number {
  const y = year + (month - 0.5) / 12;
  let t: number;
  if (y < 1920) { t = y - 1900; return -2.79 + 1.494119 * t - 0.0598939 * t ** 2 + 0.0061966 * t ** 3 - 0.000197 * t ** 4; }
  if (y < 1941) { t = y - 1920; return 21.20 + 0.84493 * t - 0.0761 * t ** 2 + 0.0020936 * t ** 3; }
  if (y < 1961) { t = y - 1950; return 29.07 + 0.407 * t - t ** 2 / 233 + t ** 3 / 2547; }
  if (y < 1986) { t = y - 1975; return 45.45 + 1.067 * t - t ** 2 / 260 - t ** 3 / 718; }
  if (y < 2005) { t = y - 2000; return 63.86 + 0.3345 * t - 0.060374 * t ** 2 + 0.0017275 * t ** 3 + 0.000651814 * t ** 4 + 0.00002373599 * t ** 5; }
  if (y < 2050) { t = y - 2000; return 62.92 + 0.32217 * t + 0.005589 * t ** 2; }
  if (y < 2150) { return -20 + 32 * ((y - 1820) / 100) ** 2 - 0.5628 * (2150 - y); }
  const u = (y - 1820) / 100; return -20 + 32 * u * u;
}

/** UT 율리우스일 → TT(JDE) */
export function jdeFromJd(jd: number): number {
  const c = civilFromJd(jd);
  return jd + deltaT(c.y, c.m) / 86400;
}
export function jdFromJde(jde: number): number {
  const c = civilFromJd(jde);
  return jde - deltaT(c.y, c.m) / 86400;
}

