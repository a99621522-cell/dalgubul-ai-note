function norm(s: string): string {
  return s.replace(/\s+/g, '').replace(/(색깔|색|빛깔|빛|쪽|방향|방|편)$/u, '').replace(/(이|가|을|를|은|는)$/u, '');
}

export interface ImageHit { trigram: TrigramName; matched: string; source: 'ko' | 'classic' | 'direction' }

/** 방위 낱말 → 괘 (後天八卦 방위) */
export function directionTrigram(word: string): ImageHit | null {
  const w = norm(word).toUpperCase();
  for (const [t, keys] of DIRECTIONS) if (keys.some((k) => k.toUpperCase() === w)) return { trigram: t, matched: word.trim(), source: 'direction' };
  return null;
}

/** 사물·사람·색 낱말 → 괘. 한글 표 → 원문 한자 목록 순으로 찾고, 정확히 같은 낱말이 없으면 포함 관계로 찾는다 */
export function objectTrigram(word: string): ImageHit | null {
  const w = norm(word);
  if (!w) return null;
  const names = Object.keys(KO_IMAGES) as TrigramName[];
  // 1) 전체 또는 띄어 쓴 낱말 하나가 표와 정확히 같을 때 (긴 낱말 우선)
  const tokens = [w, ...word.trim().split(/\s+/).map(norm).filter(Boolean)].sort((a, b) => b.length - a.length);
  for (const tk of tokens) {
    for (const t of names) if (KO_IMAGES[t].includes(tk)) return { trigram: t, matched: tk, source: 'ko' };
    for (const t of names) if (CLASSIC_IMAGES[t].includes(tk)) return { trigram: t, matched: tk, source: 'classic' };
  }
  // 2) 포함 관계
  let best: ImageHit | null = null;
  for (const t of names) {
    for (const k of [...KO_IMAGES[t], ...CLASSIC_IMAGES[t]]) {
      if (k.length >= 2 && (w.includes(k) || k.includes(w)) && (!best || k.length > best.matched.length)) best = { trigram: t, matched: k, source: KO_IMAGES[t].includes(k) ? 'ko' : 'classic' };
    }
  }
  return best;
}

/** 사용자 안내용: 괘별 대표 한글 낱말 */
export function imageHints(): Record<TrigramName, string> {
  const out = {} as Record<TrigramName, string>;
  for (const t of Object.keys(KO_IMAGES) as TrigramName[]) out[t] = KO_IMAGES[t].slice(0, 8).join('·');
  return out;
}
