def rd(p):
    return list(csv.DictReader(open(p, encoding='utf-8-sig')))


def f(v, d=1):
    return '—' if v in (None, '') else f'{float(v):,.{d}f}'


def tbl(head, rows):
    return '\n'.join(['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)] + ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows])


def fig(name, spec):
    j = FIG / f'{name}.json'
    j.write_text(json.dumps(spec, ensure_ascii=False), encoding='utf-8')
    svg = FIG / f'{name}.svg'
    subprocess.run([sys.executable, str(R / 'scripts/figure.py'), str(j), '-o', str(svg)], check=True, capture_output=True)
    subprocess.run(['rsvg-convert', '-z', '2', '-b', 'white', '-o', str(FIG / f'{name}.png'), str(svg)], check=True)
    j.unlink()
    return f'fig/{name}.png'


