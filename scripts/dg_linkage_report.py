def rd(name):
    p = D / name
    return list(csv.DictReader(open(p, encoding='utf-8-sig'))) if p.exists() else []


def f(v, d=1):
    if v in (None, ''):
        return '—'
    v = float(v)
    return f'{v:,.{d}f}'


def tbl(head, rows):
    out = ['| ' + ' | '.join(head) + ' |', '|' + '---|' * len(head)]
    out += ['| ' + ' | '.join(str(c) for c in r) + ' |' for r in rows]
    return '\n'.join(out)


def fig(name, spec):
    j = FIG / f'{name}.json'
    j.write_text(json.dumps(spec, ensure_ascii=False), encoding='utf-8')
    svg = FIG / f'{name}.svg'
    subprocess.run([sys.executable, str(R / 'scripts/figure.py'), str(j), '-o', str(svg)], check=True, capture_output=True)
    subprocess.run(['rsvg-convert', '-z', '2', '-b', 'white', '-o', str(FIG / f'{name}.png'), str(svg)], check=True)
    return f'fig/{name}.png'


